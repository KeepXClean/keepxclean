const SUPPORTED_LOCALE_SET = new Set<string>(SUPPORTED_LOCALES);

export function isSupportedLocale(value: unknown): value is SupportedLocale {
  return typeof value === 'string' && SUPPORTED_LOCALE_SET.has(value);
}

export function isUILocaleSetting(value: unknown): value is UILocaleSetting {
  return value === 'auto' || isSupportedLocale(value);
}

export function detectRuntimeLanguage(): string {
  try {
    const g = globalThis as {
      chrome?: { i18n?: { getUILanguage?: () => string } };
      navigator?: { language?: string };
    };
    const chromeLang = g.chrome?.i18n?.getUILanguage?.();
    if (typeof chromeLang === 'string' && chromeLang.trim()) {
      return chromeLang.trim();
    }
    const navLang = g.navigator?.language;
    if (typeof navLang === 'string' && navLang.trim()) {
      return navLang.trim();
    }
  } catch {
    // Ignore outside browser/extension contexts
  }
  return 'en';
}

export function resolveLocale(
  setting?: UILocaleSetting,
  envLang?: string
): SupportedLocale {
  if (setting && setting !== 'auto' && isSupportedLocale(setting)) {
    return setting;
  }
  const raw = (envLang ?? detectRuntimeLanguage())
    .trim()
    .replace(/_/g, '-')
    .toLowerCase();
  if (!raw) return 'en';
  if (raw.startsWith('zh')) {
    if (
      raw.includes('tw') ||
      raw.includes('hk') ||
      raw.includes('mo') ||
      raw.includes('hant')
    ) {
      return 'zh-TW';
    }
    return 'zh-CN';
  }
  if (raw.startsWith('ja')) return 'ja';
  if (raw.startsWith('ko')) return 'ko';
  if (raw.startsWith('es')) return 'es';
  if (raw.startsWith('pt')) return 'pt';
  if (raw.startsWith('fr')) return 'fr';
  if (raw.startsWith('de')) return 'de';
  if (raw.startsWith('ru')) return 'ru';
  if (raw.startsWith('en')) return 'en';
  return 'en';
}

